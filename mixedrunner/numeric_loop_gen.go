package main

import (
	"go/format"
	"os"
	"strings"
)

func main() {
	source, err := os.ReadFile("mixed_typed_runner.go")
	if err != nil {
		panic(err)
	}
	s := string(source)
	start := strings.Index(s, "\tvar initial [3]mixedFrame")
	end := strings.Index(s[start:], "\n// Frames belong") + start
	s = s[start:end]
	replace := func(old, new string) {
		if strings.Count(s, old) != 1 {
			panic("numeric loop source changed: " + old)
		}
		s = strings.Replace(s, old, new, 1)
	}
	remove := func(first, last string) {
		a := strings.Index(s, first)
		if a < 0 {
			panic("numeric loop source changed: " + first)
		}
		b := strings.Index(s[a:], last)
		if b < 0 {
			panic("numeric loop source changed: " + last)
		}
		s = s[:a] + s[a+b:]
	}
	s = strings.ReplaceAll(s, "mixedFrame", "mixedNumericFrame")
	remove("\tif r.refSlots != 0 {", "\tcopy(regs[:]")
	remove("\t\tif k == types.Invalid {", "\n\t}\n\t// Frame")
	replace("\tfor i, k := range r.params {\n\n\t}", "\tfor i, k := range r.params {\n\t\tregs[i] = mixedUnbox(args[i], k)\n\t}")
	remove("\t\tcase mixedFieldAddr:", "\t\tcase mixedAdd:")
	remove("\n\t\t\t\tif len(next.refs)", "\n\t\t\t}")
	remove("\t\t\tfor _, i := range op.callee.refParams", "\t\t\tcode, pc =")
	remove("\t\t\tif n := frames[depth].runner.refSlots", "\t\t\tcode, pc, regs =")
	s = `// Code generated by numeric_loop_gen.go; DO NOT EDIT.

package mixedrunner

import "github.com/goplus/ixgo"

// runNumeric executes graphs without reference slots, using the same numeric operations as RunArgs.
func (r *mixedTypedRunner) runNumeric(args []ixgo.Value) ixgo.Value {
` + s + `
type mixedNumericFrame struct {
	runner *mixedTypedRunner
	code []mixedOp
	pc int
	regs [mixedArgsLimit]uint64
}
`
	output, err := format.Source([]byte(s))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("numeric_loop.go", output, 0644); err != nil {
		panic(err)
	}
}
